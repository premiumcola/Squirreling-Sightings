// ─── netz/index.js ─────────────────────────────────────────────────────────
// Erkennungsprofil — public API, hydration, view router, window.* bridge.
//
// One page (#netz), two views rendered into the same host (#netzBody):
// the nets and the Verlauf (archive). Only one is in the DOM at a time,
// so the back button navigates between them for free and there is no
// modal-inside-a-modal on iOS.
//
//   #netz                           → die Netze
//   #netz?tab=verlauf               → das Archiv
//   #netz?tab=verlauf&filter=offen  → the 07:00 Telegram message's target
//                                     (built server-side in
//                                     telegram_bot/_outbound/_question.py)
//
// The `tab=` query name is kept even though the tab BAR is gone: that
// deep link is generated by the bot and lives in messages already sent.

import { byId } from '../core/dom.js';
import { showToast } from '../core/toast.js';
import { fetchArchive, fetchArchiveRecord, fetchState } from './_api.js';
import { bindCards, renderCards } from './_cards.js';
import { bindTuneDrag, isTuneDragging } from './_tune_drag.js';
import { renderTuneRadar } from './_tune_radar.js';
import { buildTuneAxes } from './_settings_axes.js';
import { renderArchiveDetail } from './_archive_detail.js';
import { renderArchiveList } from './_archive_list.js';
import { effectiveTuning, netzState } from './_state.js';

const HOST_ID = 'netzBody';

function _host() {
  return byId(HOST_ID);
}

// ── Netz view ─────────────────────────────────────────────────────────

function renderNet(host) {
  renderCards(host);
  bindCards(host, () => renderNet(host));
  bindTuneDrag(host, () => renderNet(host));
}

// A vertex mid-drag repaints only its own card's SVG. A full re-render
// would rebuild the node under the finger and drop the pointer capture.
function _onVertexMove(host, { camId, key, e }) {
  const card = host.querySelector(`.netz-card[data-cam="${CSS.escape(camId)}"]`);
  const wrap = card?.querySelector('.netz-card-chart');
  if (!wrap) return;
  const axes = buildTuneAxes(effectiveTuning(camId));
  const i = axes.findIndex((a) => a.key === key);
  if (i < 0) return;
  axes[i] = { ...axes[i], E: e };
  netzState.tuneAxes[camId] = axes;
  wrap.innerHTML = renderTuneRadar({ axes, interactive: true });
  // Fresh nodes need fresh listeners for the NEXT drag; the current one
  // keeps running on its captured node regardless.
  bindTuneDrag(host, () => renderNet(host));
}

export async function loadNet() {
  const host = _host();
  if (!host) return;
  netzState.loading = true;
  // First paint needs the camera list; /api/netz/state carries it for
  // whichever camera answers first, so ask once and then fan out.
  const seed = await fetchState(netzState.cameras[0]?.id || null);
  if (seed.ok) {
    netzState.cameras = seed.cameras || [];
    netzState.states[seed.cam_id] = seed;
  }
  const rest = (netzState.cameras || []).filter((c) => c.id !== seed.cam_id);
  const others = await Promise.all(rest.map((c) => fetchState(c.id)));
  others.forEach((r) => {
    if (r && r.ok) netzState.states[r.cam_id] = r;
  });
  netzState.loading = false;
  if (netzState.view === 'netz') renderNet(host);
}

// ── Verlauf view ──────────────────────────────────────────────────────

async function loadArchive() {
  const host = _host();
  if (!host) return;
  const res = await fetchArchive({ ...netzState.archiveFilter });
  netzState.archive = res.ok ? res : { items: [] };
  renderArchiveList(host, netzState.archive, {
    reload: loadArchive,
    openDetail: openArchiveDetail,
  });
}

async function openArchiveDetail(eid) {
  const host = _host();
  if (!host) return;
  netzState.archiveView = 'detail';
  netzState.detailId = eid;
  const res = await fetchArchiveRecord(eid);
  if (!res.ok || netzState.detailId !== eid) {
    showToast('Datensatz nicht gefunden.', 'warn');
    netzState.archiveView = 'list';
    return loadArchive();
  }
  const row = (netzState.archive?.items || []).find((r) => r.event_id === eid);
  netzState.detail = { ...res.record, badge: row?.badge || '⏳' };
  renderArchiveDetail(host, netzState.detail, {
    back: () => {
      netzState.archiveView = 'list';
      loadArchive();
    },
    afterRestore: (state) => {
      if (state && state.cam_id) netzState.states[state.cam_id] = state;
      netzState.archiveView = 'list';
      loadArchive();
    },
  });
}

// ── view routing ──────────────────────────────────────────────────────

function _paintToggle() {
  const btn = byId('netzViewBtn');
  if (!btn) return;
  const toArchive = netzState.view === 'netz';
  btn.setAttribute('aria-label', toArchive ? 'Verlauf öffnen' : 'Zurück zu den Netzen');
  btn.setAttribute('title', toArchive ? 'Verlauf' : 'Zurück zu den Netzen');
  btn.dataset.view = netzState.view;
}

export function showTab(tab) {
  netzState.view = tab === 'verlauf' ? 'verlauf' : 'netz';
  _paintToggle();
  if (netzState.view === 'verlauf') {
    netzState.archiveView = 'list';
    loadArchive();
  } else {
    loadNet();
  }
}

function _routeFromHash() {
  const h = location.hash || '';
  if (!h.startsWith('#netz')) return;
  const q = h.includes('?') ? new URLSearchParams(h.slice(h.indexOf('?') + 1)) : null;
  if (q?.get('filter') === 'offen') netzState.archiveFilter.open = true;
  showTab(q?.get('tab') || 'netz');
}

let _observer = null;

/** Hydrate on first visibility, matching storms/. The panel is a section
 *  the operator scrolls into, not a background task. */
export function initNetz() {
  const sec = byId('netz');
  if (!sec || _observer) return;
  byId('netzViewBtn')?.addEventListener('click', () => {
    showTab(netzState.view === 'netz' ? 'verlauf' : 'netz');
  });
  _observer = new IntersectionObserver(
    (entries) => {
      if (entries.some((e) => e.isIntersecting)) _routeFromHash();
    },
    { threshold: 0.02 },
  );
  _observer.observe(sec);
  if ((location.hash || '').startsWith('#netz')) _routeFromHash();
  const host = _host();
  host?.addEventListener('netz:tunevertexmove', (ev) => _onVertexMove(host, ev.detail));
}

window.addEventListener('hashchange', () => {
  if ((location.hash || '').startsWith('#netz')) _routeFromHash();
});

// Re-draw on resize so the viewBox keeps its uniform mapping through a
// rotation or a window drag. Debounced, and skipped mid-drag.
let _resizeTimer = null;
window.addEventListener(
  'resize',
  () => {
    if (!_host() || netzState.view !== 'netz' || isTuneDragging()) return;
    if (_resizeTimer) clearTimeout(_resizeTimer);
    _resizeTimer = setTimeout(() => renderNet(_host()), 180);
  },
  { passive: true },
);

document.addEventListener('DOMContentLoaded', initNetz);

// window.* bridge — live-update.js's loadAll() reaches domain
// bootstrappers by global name, matching initStorms next door.
window.initNetz = initNetz;
